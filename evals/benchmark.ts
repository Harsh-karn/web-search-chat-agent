// Optional live comparison harness. Never part of deterministic CI.
import dotenv from "dotenv";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { runAgentTurn } from "../src/agent/loop";
dotenv.config({ path: ".env.local" });
process.env.DATABASE_PATH = join(
  mkdtempSync(join(tmpdir(), "agent-benchmark-")),
  "benchmark.db",
);
const cases = [
  { id: "stable", query: "What is binary search?", searchExpected: false },
  {
    id: "fresh",
    query: "What changed in PostgreSQL releases this week?",
    searchExpected: true,
  },
  {
    id: "ambiguous",
    query: "Is Mercury better than Apollo?",
    searchExpected: false,
  },
  {
    id: "multipart",
    query:
      "Compare current pricing for Supabase and Neon for a small production app.",
    searchExpected: true,
  },
  {
    id: "followup",
    query: "Which of those would suit a small team with variable traffic?",
    searchExpected: false,
    previous: "multipart",
  },
  {
    id: "conflict",
    query:
      "Find conflicting evidence about whether serverless Postgres is always cheaper; explain the conditions.",
    searchExpected: true,
  },
  {
    id: "missing-history",
    query: "What did I ask you on January 1 2001?",
    searchExpected: false,
  },
  {
    id: "insufficient",
    query:
      "What is the verified launch date of the fictional Zebralight 9000 database?",
    searchExpected: true,
  },
];
async function main() {
  if (!process.env.GEMINI_API_KEY && !process.env.GOOGLE_GENERATIVE_AI_API_KEY)
    throw Error("Configure a model API key for this optional live benchmark");
  if (!process.env.TAVILY_API_KEY)
    throw Error("Configure Tavily for this optional live benchmark");
  const runs = [];
  for (const c of cases) {
    let calls = 0;
    const start = performance.now();
    let firstTokenMs: number | null = null;
    let answer = "";
    const turn = runAgentTurn({
      userId: `benchmark-${c.previous || c.id}`,
      messages: [{ id: c.id, role: "user", content: c.query }],
      onToolCall: () => {
        calls++;
      },
    });
    for await (const chunk of turn.streamResult.textStream) {
      if (firstTokenMs === null) firstTokenMs = performance.now() - start;
      answer += chunk;
    }
    runs.push({
      ...c,
      answer,
      latencyMs: performance.now() - start,
      firstTokenMs,
      searchCalls: calls,
      modelSteps: (await turn.streamResult.steps).length,
      usage: await turn.streamResult.usage,
      searchDecisionMatches: calls > 0 === c.searchExpected,
      manualReview: {
        correctness: null,
        retrievalRelevance: null,
        citationSupport: null,
        followupConsistency: null,
      },
    });
  }
  const latency = runs.map((r) => r.latencyMs).sort((a, b) => a - b);
  const report = {
    provenance:
      "Generated by CodeRabbit implementation; benchmark observations require human calibration.",
    model: process.env.GEMINI_MODEL || "gemini-2.5-flash",
    at: new Date().toISOString(),
    meanLatencyMs: latency.reduce((a, b) => a + b, 0) / latency.length,
    p95LatencyMs: latency[Math.ceil(latency.length * 0.95) - 1],
    runs,
  };
  writeFileSync(
    process.argv[2] || "/tmp/agent-benchmark.json",
    JSON.stringify(report, null, 2),
  );
}
main().catch((e) => {
  console.error(e.message);
  process.exitCode = 1;
});
